/* Packs games/rough-ride/sfx/* into games/rough-ride/sfx.js (base64), so the sounds load even when the
   arcade is opened straight from disk. To swap a sound: replace the file in sfx/ (same name), then run
     node tools/rough-ride-sfx.js
   Names used by the game: shot, reload, boom1..boomN (small explosions, picked at random),
   bigboom (vehicles), megaboom (bosses, gunship, BOOM crate), engine (seamless loop). */
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'games', 'rough-ride', 'sfx'), out = {};
for (const f of fs.readdirSync(dir).sort()) if (/\.(mp3|ogg|wav)$/i.test(f)) out[f.replace(/\.\w+$/, '')] = fs.readFileSync(path.join(dir, f)).toString('base64');
fs.writeFileSync(path.join(dir, '..', 'sfx.js'), '/* generated by tools/rough-ride-sfx.js - do not edit by hand */\nwindow.RR_SFX = ' + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ';\n');
console.log('packed', Object.keys(out).join(', '));
